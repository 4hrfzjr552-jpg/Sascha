// Standalone Node.js 22+ worker. Deploy on a persistent server or scheduled job.
// Never ship SUPABASE_SERVICE_ROLE_KEY to browsers, mobile apps or GitHub.
import 'dotenv/config';
import { createClient } from '@supabase/supabase-js';
import { randomUUID } from 'node:crypto';

const required = ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY', 'CLOUD_APP_URL'];
for (const key of required) {
  if (!process.env[key]) throw new Error(`Missing environment variable: ${key}`);
}
const origin = new URL(process.env.CLOUD_APP_URL);
if (!['https:', 'http:'].includes(origin.protocol) ||
    (origin.protocol === 'http:' && origin.hostname !== 'localhost')) {
  throw new Error('CLOUD_APP_URL must be HTTPS (or localhost for development).');
}
const supabase = createClient(
  process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY,
  { auth: { persistSession: false, autoRefreshToken: false } }
);
const workerId = process.env.CLOUD_WORKER_ID || randomUUID();
const pollMs = Math.max(3000, Number(process.env.CLOUD_POLL_MS) || 10000);
let stopped = false;
process.on('SIGTERM', () => { stopped = true; });
process.on('SIGINT', () => { stopped = true; });
const sleep = (ms) => new Promise(resolve => setTimeout(resolve, ms));
const errorText = e => String(e instanceof Error ? e.message : e).slice(0, 500);

async function markJob(job, status, error = null) {
  const { error: updateError } = await supabase.from('cloud_jobs').update({
    status, error, lease_until: null, finished_at: new Date().toISOString(),
    updated_at: new Date().toISOString(),
  }).eq('id', job.id).eq('worker_id', workerId).eq('status', 'running');
  if (updateError) throw updateError;
}

async function analyzeJob(job) {
  const { data: row, error } = await supabase.from('pants')
    .select('id,user_id,data,updated_at')
    .eq('id', job.pant_id).eq('user_id', job.user_id).single();
  if (error || !row) throw new Error('Artikel fehlt oder gehört nicht zum Auftraggeber.');
  const pant = typeof row.data === 'string' ? JSON.parse(row.data) : row.data;
  if (!pant || !String(pant.artikelnummer ?? '').trim()) {
    throw new Error('Artikelnummer fehlt.');
  }
  const savedImages = (Array.isArray(pant.images) ? pant.images : [])
    .filter(image => typeof image.storagePath === 'string' && image.storagePath.length > 0)
    .slice(0, 5);
  if (savedImages.length === 0) {
    throw new Error('Keine hochgeladenen Supabase-Bilder. Bilder zuerst synchronisieren.');
  }
  const images = [];
  for (const image of savedImages) {
    // Only signed URLs generated by our own Supabase Storage, not arbitrary URLs.
    if (!image.storagePath.startsWith(job.user_id + '/' + row.id + '/')) {
      throw new Error('Bild gehört nicht zu diesem Artikel.');
    }
    const { data, error: signError } = await supabase.storage
      .from('pant-images').createSignedUrl(image.storagePath, 300);
    if (signError || !data?.signedUrl) throw new Error('Bild-URL konnte nicht erstellt werden.');
    images.push({ id: image.id, dataUrl: data.signedUrl });
  }
  const apiUrl = new URL('/api/analyze-pant', origin);
  const response = await fetch(apiUrl, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      number: pant.number, artikelnummer: pant.artikelnummer,
      images, measurements: pant.measurements, customNotes: pant.customNotes,
      // Server uses its existing default instructions; browser-only prompt
      // preferences are intentionally not read by an unattended worker.
    }),
    signal: AbortSignal.timeout(180000),
  });
  let body;
  try { body = await response.json(); }
  catch { throw new Error(`KI-Server hat HTTP ${response.status} ohne gültiges JSON geliefert.`); }
  if (!response.ok || !body?.success || !body?.data?.title) {
    throw new Error(body?.error || `KI-Anfrage fehlgeschlagen: HTTP ${response.status}`);
  }

  // Optimistic write: never overwrite changes a seller made while AI was busy.
  const next = {
    ...pant, result: body.data, status: 'done', errorMessage: undefined,
    updatedAt: Date.now(),
  };
  let query = supabase.from('pants')
    .update({ data: next, updated_at: new Date().toISOString() })
    .eq('id', row.id).eq('user_id', job.user_id);
  if (row.updated_at) query = query.eq('updated_at', row.updated_at);
  const { data: changed, error: saveError } = await query.select('id');
  if (saveError) throw saveError;
  if (!changed?.length) throw new Error('Artikel wurde zwischenzeitlich geändert. Keine Daten überschrieben.');
}

async function processOne() {
  const { data, error } = await supabase.rpc('claim_cloud_analysis_job', { p_worker_id: workerId });
  if (error) throw error;
  const job = data?.[0];
  if (!job) return false;
  console.log(`[cloud] running job ${job.id} for pant ${job.pant_id}`);
  try {
    await analyzeJob(job);
    await markJob(job, 'completed');
    console.log(`[cloud] completed ${job.id}`);
  } catch (e) {
    const reason = errorText(e);
    console.error(`[cloud] failed ${job.id}: ${reason}`);
    await markJob(job, 'failed', reason);
  }
  return true;
}

console.log(`[cloud] worker ${workerId} started (poll every ${pollMs}ms)`);
while (!stopped) {
  try {
    const worked = await processOne();
    if (!worked) await sleep(pollMs);
  } catch (e) {
    console.error('[cloud] queue error:', errorText(e));
    await sleep(pollMs);
  }
}
console.log('[cloud] stopped');
